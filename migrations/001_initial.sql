-- Enable required extensions
CREATE EXTENSION IF NOT EXISTS "pgcrypto";   -- gen_random_uuid()
CREATE EXTENSION IF NOT EXISTS "pg_stat_statements";

-- =============================================================================
-- 1. Main audit log table (partitioned)
-- =============================================================================

CREATE TABLE IF NOT EXISTS api_audit_log (
    id                  UUID            NOT NULL DEFAULT gen_random_uuid(),
    timestamp_utc       TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    client_id           VARCHAR(100)    NOT NULL,
    user_sub            VARCHAR(200),
    method              VARCHAR(10)     NOT NULL,
    endpoint            VARCHAR(500)    NOT NULL,
    query_params        JSONB,
    request_body_hash   VARCHAR(64),
    scopes_used         TEXT[],
    ip_origin           INET            NOT NULL,
    user_agent          VARCHAR(500),
    http_status         SMALLINT        NOT NULL,
    response_time_ms    INTEGER         NOT NULL,
    error_code          VARCHAR(50),
    error_message       VARCHAR(500),
    records_returned    INTEGER,
    token_jti           UUID,
    geo_country         VARCHAR(3),
    geo_city            VARCHAR(100),
    flagged             BOOLEAN         NOT NULL DEFAULT FALSE,
    flag_reason         VARCHAR(200),
    PRIMARY KEY (id, timestamp_utc)
) PARTITION BY RANGE (timestamp_utc);

COMMENT ON TABLE api_audit_log IS
    'Immutable audit log — one row per API request. Partitioned by month.';

COMMENT ON COLUMN api_audit_log.id IS 'UUID primary key, generated by PostgreSQL';
COMMENT ON COLUMN api_audit_log.timestamp_utc IS 'Request completion timestamp (UTC)';
COMMENT ON COLUMN api_audit_log.client_id IS 'OAuth 2.0 client_id extracted from the JWT';
COMMENT ON COLUMN api_audit_log.user_sub IS 'End-user subject (Authorization Code flow only)';
COMMENT ON COLUMN api_audit_log.endpoint IS 'Normalised path with {param} placeholders';
COMMENT ON COLUMN api_audit_log.request_body_hash IS 'SHA-256 hex digest of POST/PUT/PATCH body';
COMMENT ON COLUMN api_audit_log.scopes_used IS 'OAuth 2.0 scopes present in the JWT';
COMMENT ON COLUMN api_audit_log.ip_origin IS 'Client IP (X-Forwarded-For aware)';
COMMENT ON COLUMN api_audit_log.token_jti IS 'JWT ID claim for revocation tracking';
COMMENT ON COLUMN api_audit_log.flagged IS 'True when flagged by an anomaly detection rule';

