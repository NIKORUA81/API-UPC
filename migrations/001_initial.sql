-- =============================================================================
-- 3. Indexes
-- =============================================================================

-- Index 1: Time-range scans (most common query pattern)
CREATE INDEX IF NOT EXISTS idx_audit_timestamp
    ON api_audit_log (timestamp_utc DESC);

-- Index 2: Per-client queries (security investigation, billing)
CREATE INDEX IF NOT EXISTS idx_audit_client_timestamp
    ON api_audit_log (client_id, timestamp_utc DESC);

-- Index 3: Endpoint performance analysis
CREATE INDEX IF NOT EXISTS idx_audit_endpoint_timestamp
    ON api_audit_log (endpoint, timestamp_utc DESC);

-- Index 4: Flagged / anomalous records
CREATE INDEX IF NOT EXISTS idx_audit_flagged
    ON api_audit_log (flagged, timestamp_utc DESC)
    WHERE flagged = TRUE;

-- =============================================================================
-- 4. Materialized view: daily summary
-- =============================================================================

CREATE MATERIALIZED VIEW IF NOT EXISTS audit_resumen_diario AS
SELECT
    DATE_TRUNC('day', timestamp_utc)::DATE          AS fecha,
    client_id,
    endpoint,
    COUNT(*)                                         AS total_requests,
    COUNT(*) FILTER (WHERE http_status >= 400
                       AND http_status < 500)        AS errores_4xx,
    COUNT(*) FILTER (WHERE http_status >= 500)       AS errores_5xx,
    ROUND(AVG(response_time_ms))                     AS avg_response_time_ms,
    PERCENTILE_CONT(0.95) WITHIN GROUP
        (ORDER BY response_time_ms)                  AS p95_response_time_ms,
    MAX(response_time_ms)                            AS max_response_time_ms,
    COUNT(DISTINCT ip_origin::TEXT)                  AS unique_ips,
    COUNT(*) FILTER (WHERE flagged = TRUE)           AS flagged_count
FROM api_audit_log
GROUP BY
    DATE_TRUNC('day', timestamp_utc)::DATE,
    client_id,
    endpoint
WITH DATA;

COMMENT ON MATERIALIZED VIEW audit_resumen_diario IS
    'Daily aggregated audit summary per client and endpoint. Refresh with REFRESH MATERIALIZED VIEW CONCURRENTLY audit_resumen_diario.';

-- Index for fast daily lookups on the materialized view
CREATE UNIQUE INDEX IF NOT EXISTS idx_resumen_diario_pk
    ON audit_resumen_diario (fecha, client_id, endpoint);

CREATE INDEX IF NOT EXISTS idx_resumen_diario_fecha
    ON audit_resumen_diario (fecha DESC);

-- =============================================================================
-- Refresh helper function
-- =============================================================================

CREATE OR REPLACE FUNCTION refresh_audit_resumen_diario()
RETURNS VOID
LANGUAGE plpgsql
AS $$
BEGIN
    REFRESH MATERIALIZED VIEW CONCURRENTLY audit_resumen_diario;
END;
$$;

COMMENT ON FUNCTION refresh_audit_resumen_diario() IS
    'Refresh the daily audit summary materialized view concurrently. Schedule via pg_cron or external scheduler.';
